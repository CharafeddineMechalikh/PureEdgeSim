package com.mechalikh.pureedgesim.scenariomanager;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Comparator;
import java.util.Properties;
import java.util.regex.Matcher;

/**
 * Helper used by the scenario manager tests to create temporary (often
 * malformed) configuration files under target/test-tmp/.
 */
final class TempSettingsFiles {

	static final Path DIR = Paths.get("target", "test-tmp", "scenariomanager");
	static final Path SETTINGS = Paths.get("PureEdgeSim", "test", "resources", "test-settings");

	private TempSettingsFiles() {
	}

	static void resetDirectory() throws IOException {
		if (Files.exists(DIR)) {
			Files.walk(DIR).sorted(Comparator.reverseOrder()).forEach(path -> {
				try {
					Files.deleteIfExists(path);
				} catch (IOException e) {
					throw new IllegalStateException(e);
				}
			});
		}
		Files.createDirectories(DIR);
	}

	static Path write(String name, String content) throws IOException {
		Files.createDirectories(DIR);
		Path file = DIR.resolve(name);
		Files.write(file, content.getBytes(StandardCharsets.UTF_8));
		return file;
	}

	static String resource(String name) throws IOException {
		return new String(Files.readAllBytes(SETTINGS.resolve(name)), StandardCharsets.UTF_8);
	}

	/**
	 * Removes the first occurrence of the given XML element (including nested
	 * content).
	 */
	static String removeFirstElement(String xml, String tag) {
		return withoutComments(xml).replaceFirst("(?s)<" + tag + "\\b[^>]*>.*?</" + tag + ">", "");
	}

	/**
	 * Replaces the content of the first occurrence of the given XML element.
	 */
	static String replaceFirstElement(String xml, String tag, String value) {
		String replacement = Matcher.quoteReplacement("<" + tag + ">" + value + "</" + tag + ">");
		return withoutComments(xml).replaceFirst("(?s)<" + tag + "\\b[^>]*>.*?</" + tag + ">", replacement);
	}

	/**
	 * Strips comments so that tag names mentioned in comments are never matched
	 * instead of the actual elements.
	 */
	private static String withoutComments(String xml) {
		return xml.replaceAll("(?s)<!--.*?-->", "");
	}

	/**
	 * Copies the fast test properties file and applies the given overrides.
	 */
	static Path propertiesWith(String key, String value) throws IOException {
		Properties properties = new Properties();
		try (java.io.InputStream in = Files.newInputStream(SETTINGS.resolve("fast.properties"))) {
			properties.load(in);
		}
		properties.setProperty(key, value);
		return store(properties, "props-" + key + "-" + Integer.toHexString(value.hashCode()) + ".properties");
	}

	static Path propertiesWithout(String key) throws IOException {
		Properties properties = new Properties();
		try (java.io.InputStream in = Files.newInputStream(SETTINGS.resolve("fast.properties"))) {
			properties.load(in);
		}
		properties.remove(key);
		return store(properties, "props-without-" + key + ".properties");
	}

	static Path propertiesWithTwo(String key1, String value1, String key2, String value2) throws IOException {
		Properties properties = new Properties();
		try (java.io.InputStream in = Files.newInputStream(SETTINGS.resolve("fast.properties"))) {
			properties.load(in);
		}
		properties.setProperty(key1, value1);
		properties.setProperty(key2, value2);
		return store(properties, "props-two-" + key1 + "-" + key2 + ".properties");
	}

	static Path propertiesWithOverrides(java.util.Map<String, String> overrides, String name) throws IOException {
		Properties properties = new Properties();
		try (java.io.InputStream in = Files.newInputStream(SETTINGS.resolve("fast.properties"))) {
			properties.load(in);
		}
		properties.putAll(overrides);
		return store(properties, name);
	}

	private static Path store(Properties properties, String name) throws IOException {
		Files.createDirectories(DIR);
		Path file = DIR.resolve(name);
		try (OutputStream out = Files.newOutputStream(file)) {
			properties.store(out, "generated by tests");
		}
		return file;
	}
}
