package com.mechalikh.pureedgesim.locationmanager;

import java.util.ArrayList;
import java.util.List;
import java.util.Random;

import com.mechalikh.pureedgesim.scenariomanager.SimulationParameters;
import com.mechalikh.pureedgesim.simulationmanager.SimulationManager;

/**
 * Reference point group mobility model. All the devices that share the same
 * {@code group} option follow one reference point that moves across the
 * simulation area, while every device keeps the position it had relative to that
 * point at the start of the simulation.
 * <p>
 * This is the standard model for a crowd, a platoon of vehicles or a team of
 * workers that moves together, and it is what makes handovers correlated between
 * devices: members of a group leave and re-enter the range of an edge data center
 * at the same time.
 * <p>
 * The path of the reference point is generated by the random waypoint process and
 * is derived only from the group name, so members of a group always agree on it
 * without having to share any state. Devices placed by the scenario generator
 * only need to use the same {@code group} value, and the same anchor options, to
 * move together.
 * <p>
 * Options, read from the attributes of the {@code <mobility>} element:
 * <ul>
 * <li>{@code group}: name that identifies the group. Default {@code "1"}.</li>
 * <li>{@code anchor_speed}: speed of the reference point, in meters per second.
 * Default: the speed of the device.</li>
 * <li>{@code anchor_pause}: pause taken by the reference point at each waypoint,
 * in seconds. Default 0.</li>
 * </ul>
 * Select it with
 * {@code <mobility model="group" group="buses" anchor_speed="15">true</mobility>}.
 *
 * @author Charafeddine Mechalikh
 * @since PureEdgeSim 5.7
 */
public class ReferencePointGroupMobilityModel extends MobilityModel {

	/** Path of the reference point, one location per update tick. */
	protected List<Location> anchorPath;
	/** Position of the device relative to the reference point, in meters. */
	protected Location offset;
	/** Index of the next tick, used to read the reference point path. */
	protected int tick;

	/**
	 * Creates a group mobility model for a node at the given location.
	 *
	 * @param simulationManager the simulation manager
	 * @param currentLocation   the initial location
	 */
	public ReferencePointGroupMobilityModel(SimulationManager simulationManager, Location currentLocation) {
		super(simulationManager, currentLocation);
	}

	/**
	 * Returns the position of the device next to the reference point of its group at
	 * the next tick.
	 *
	 * @param location the current location
	 * @return the location at the next update
	 */
	@Override
	protected Location getNextLocation(Location location) {
		if (anchorPath == null) {
			anchorPath = generateAnchorPath();
			offset = new Location(location.getXPos() - anchorPath.get(0).getXPos(),
					location.getYPos() - anchorPath.get(0).getYPos());
		}
		tick = Math.min(tick + 1, anchorPath.size() - 1);
		Location anchor = anchorPath.get(tick);
		return reflectLocation(
				new Location(anchor.getXPos() + offset.getXPos(), anchor.getYPos() + offset.getYPos()));
	}

	/**
	 * Builds the path of the reference point with a random waypoint process.
	 *
	 * @return one location per update tick, starting from a random position inside
	 *         the simulation area
	 */
	protected List<Location> generateAnchorPath() {
		String group = getParameter("group", "1");
		double anchorSpeed = getParameter("anchor_speed", getSpeed());
		double anchorPause = getParameter("anchor_pause", 0);
		// The path depends only on the group and on the scenario dimensions, so every
		// member of the group generates exactly the same one.
		Random anchorRandom = new Random(
				group.hashCode() * 1000003L + (long) SimulationParameters.simulationDuration);
		List<Location> path = new ArrayList<>(getTicksCount());
		Location anchor = new Location(anchorRandom.nextDouble() * getMapWidth(),
				anchorRandom.nextDouble() * getMapLength());
		double pauseRemaining = 0;
		Location target = null;
		double step = anchorSpeed * SimulationParameters.updateInterval;
		for (int i = 0; i < getTicksCount(); i++) {
			path.add(anchor);
			if (pauseRemaining > 0) {
				pauseRemaining -= SimulationParameters.updateInterval;
				continue;
			}
			if (target == null || reached(anchor, target, step)) {
				target = new Location(anchorRandom.nextDouble() * getMapWidth(),
						anchorRandom.nextDouble() * getMapLength());
				pauseRemaining = anchorPause;
			}
			anchor = moveTowards(anchor, target, step);
		}
		return path;
	}

	/**
	 * Returns the name of the group this device belongs to.
	 *
	 * @return the value of the {@code group} option
	 */
	public String getGroup() {
		return getParameter("group", "1");
	}

}
