package examples;

import java.util.HashMap;
import java.util.Map;

import com.mechalikh.pureedgesim.datacentersmanager.ComputingNode;
import com.mechalikh.pureedgesim.scenariomanager.SimulationParameters;
import com.mechalikh.pureedgesim.simulationengine.Event;
import com.mechalikh.pureedgesim.simulationmanager.SimulationManager;
import com.mechalikh.pureedgesim.taskgenerator.Task;
import com.mechalikh.pureedgesim.taskorchestrator.Orchestrator;

/**
 * Access-aware placement for multi-access MEC.
 * <p>
 * The orchestrator estimates, for every candidate node allowed by the
 * architecture, the time needed to transfer the request over the access link of
 * the device, the time needed to execute the task on the node, and the time the
 * node already has queued. The tier with the lowest estimate wins. Cloud
 * candidates pay an additional WAN hop.
 * <p>
 * The access link comes from the connectivity type of the device, so a task
 * generated by a cellular device is charged the cellular latency and bandwidth,
 * and a task generated by a Wi-Fi device is charged the Wi-Fi values. This makes
 * the access technology, not only the node capacity, part of the placement
 * decision.
 *
 * @since PureEdgeSim 6.0
 */
public class Example12AccessAwareOrchestrator extends Orchestrator {

	/** Number of tasks currently being executed or queued on each node. */
	private final int[] pending;
	/** Node chosen for each task that has not returned its result yet. */
	private final Map<Integer, Integer> decisions = new HashMap<>();

	/**
	 * Creates the orchestrator and checks the algorithm name declared in the
	 * settings file.
	 *
	 * @param simulationManager the simulation manager
	 */
	public Example12AccessAwareOrchestrator(SimulationManager simulationManager) {
		super(simulationManager);
		if (!"ACCESS_AWARE".equals(algorithmName))
			throw new IllegalArgumentException(getClass().getSimpleName() + " - Unknown orchestration algorithm '"
					+ algorithmName + "', expected ACCESS_AWARE.");
		pending = new int[nodeList.size()];
	}

	@Override
	protected int findComputingNode(String[] architectureLayers, Task task) {
		if (architectureLayers == null || architectureLayers.length == 0)
			return -1;
		int best = -1;
		double bestScore = Double.MAX_VALUE;
		for (int index = 0; index < nodeList.size(); index++) {
			ComputingNode node = nodeList.get(index);
			if (!offloadingIsPossible(task, node, architectureLayers))
				continue;
			double score = estimatedDelay(task, node) + queuedDelay(task, node, index);
			if (score < bestScore) {
				bestScore = score;
				best = index;
			}
		}
		if (best >= 0) {
			pending[best]++;
			decisions.put(task.getId(), best);
		}
		return best;
	}

	@Override
	public void resultsReturned(Task task) {
		Integer index = decisions.remove(task.getId());
		if (index != null && pending[index] > 0)
			pending[index]--;
	}

	@Override
	public void processEvent(Event e) {
		// This orchestrator does not schedule events.
	}

	/** The delay estimate used for the given node, exposed for the example test. */
	public double estimatedDelay(Task task, ComputingNode node) {
		return computeDelay(task, node) + accessDelay(task, node);
	}

	private double computeDelay(Task task, ComputingNode node) {
		double mips = node.getMipsPerCore();
		return mips <= 0 ? Double.MAX_VALUE : task.getLength() / mips;
	}

	private double queuedDelay(Task task, ComputingNode node, int index) {
		int cores = Math.max(1, (int) node.getNumberOfCPUCores());
		return pending[index] * computeDelay(task, node) / cores;
	}

	private double accessDelay(Task task, ComputingNode node) {
		double transfer = bits(task);
		if (node.getType() == SimulationParameters.TYPES.CLOUD)
			return uplinkDelay(task, transfer) + SimulationParameters.wanLatency
					+ transfer / SimulationParameters.wanBandwidthBitsPerSecond;
		if (node.getType() == SimulationParameters.TYPES.EDGE_DATACENTER)
			return uplinkDelay(task, transfer);
		return SimulationParameters.wifiLatency + transfer / SimulationParameters.wifiBandwidthBitsPerSecond;
	}

	private double uplinkDelay(Task task, double transfer) {
		if ("cellular".equals(task.getEdgeDevice().getEnergyModel().getConnectivityType()))
			return SimulationParameters.cellularLatency + transfer / SimulationParameters.cellularBandwidthBitsPerSecond;
		return SimulationParameters.wifiLatency + transfer / SimulationParameters.wifiBandwidthBitsPerSecond;
	}

	private static double bits(Task task) {
		return task.getFileSizeInBits() + task.getOutputSizeInBits();
	}
}
