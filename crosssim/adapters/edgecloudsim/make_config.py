"""Write EdgeCloudSim config files from the common benchmark specification.

The configs use the calibrated 40-device / 3-edge / 1-cloud topology and the
three class sizes from crosssim/scenario.json. The workload itself comes from
the shared trace via CommonLoadGenerator, not from these application rates.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CROSSSIM = HERE.parents[1]
SCN = json.loads((CROSSSIM / "scenario.json").read_text(encoding="utf-8"))
CONFIG = HERE / "config"
CONFIG.mkdir(parents=True, exist_ok=True)


def properties() -> str:
    fleet = SCN["fleet"]["n_devices"]
    cloud = SCN["cloud_tier"]
    return f"""# P1-CBS common scenario (generated by make_config.py)
simulation_time={int(SCN["simulation_time_s"])}
warm_up_period=0
file_log_enabled=true
deep_file_log_enabled=true
vm_load_check_interval=0.1
location_check_interval=0.1
ap_delay_check_interval=0
min_number_of_mobile_devices={fleet}
max_number_of_mobile_devices={fleet}
mobile_device_counter_size={fleet}
wan_propagation_delay={SCN["network"]["wan_latency_s"]}
lan_internal_delay={SCN["network"]["man_latency_s"]}
wlan_bandwidth=0
wan_bandwidth=0
gsm_bandwidth=0
number_of_host_on_cloud_datacenter=1
number_of_vm_on_cloud_host=4
core_for_cloud_vm=16
mips_for_cloud_vm={cloud["mips"]}
ram_for_cloud_vm={cloud["ram_MB"] // 4}
storage_for_cloud_vm={cloud["storage_MB"] // 4}
core_for_mobile_vm=0
mips_for_mobile_vm=0
ram_for_mobile_vm=0
storage_for_mobile_vm=0
orchestrator_policies=REFERENCE
simulation_scenarios=DEFAULT_SCENARIO
attractiveness_L1_mean_waiting_time=600
attractiveness_L2_mean_waiting_time=600
attractiveness_L3_mean_waiting_time=600
"""


def applications() -> str:
    blocks = []
    for cls in SCN["workload_classes"]:
        share = int(round(cls["device_share"] * 100))
        blocks.append(f"""\t<application name="{cls['id']}">
\t\t<usage_percentage>{share}</usage_percentage>
\t\t<prob_cloud_selection>0</prob_cloud_selection>
\t\t<poisson_interarrival>{60 / cls['rate_tasks_per_min_per_device']:.3f}</poisson_interarrival>
\t\t<delay_sensitivity>1</delay_sensitivity>
\t\t<active_period>300</active_period>
\t\t<idle_period>0</idle_period>
\t\t<data_upload>{cls['request_Kbytes']}</data_upload>
\t\t<data_download>{cls['result_Kbytes']}</data_download>
\t\t<task_length>{cls['task_length_MI']}</task_length>
\t\t<required_core>1</required_core>
\t\t<vm_utilization_on_edge>{min(100, cls['task_length_MI'] / 120.0):.3f}</vm_utilization_on_edge>
\t\t<vm_utilization_on_cloud>{min(100, cls['task_length_MI'] / 1200.0):.3f}</vm_utilization_on_cloud>
\t\t<vm_utilization_on_mobile>0</vm_utilization_on_mobile>
\t</application>""")
    return '<?xml version="1.0"?>\n<applications>\n' + "\n".join(blocks) + "\n</applications>\n"


def edge_devices() -> str:
    edge = SCN["edge_tier"]
    n_vm = 16
    per_vm_mips = edge["mips"]      # one DES replica per core, as in the YAFS adapter
    host_mips = n_vm * per_vm_mips
    per_vm_ram = edge["ram_MB"] // n_vm
    per_vm_storage = edge["storage_MB"] // n_vm
    vm_xml = "\n".join(f"""\t\t\t\t\t<VM vmm="Xen">
\t\t\t\t\t\t<core>{edge['cores'] // n_vm}</core>
\t\t\t\t\t\t<mips>{per_vm_mips}</mips>
\t\t\t\t\t\t<ram>{per_vm_ram}</ram>
\t\t\t\t\t\t<storage>{per_vm_storage}</storage>
\t\t\t\t\t</VM>""" for _ in range(n_vm))
    dcs = []
    for index in range(edge["n_datacenters"]):
        dcs.append(f"""\t<datacenter arch="x86" os="Linux" vmm="Xen">
\t\t<costPerBw>0.1</costPerBw><costPerSec>3.0</costPerSec>
\t\t<costPerMem>0.05</costPerMem><costPerStorage>0.1</costPerStorage>
\t\t<location><x_pos>{index + 1}</x_pos><y_pos>{index + 1}</y_pos>
\t\t\t<wlan_id>{index}</wlan_id><attractiveness>0</attractiveness></location>
\t\t<hosts><host>
\t\t\t<core>{edge['cores']}</core><mips>{host_mips}</mips>
\t\t\t<ram>{edge['ram_MB']}</ram><storage>{edge['storage_MB']}</storage>
\t\t\t<VMs>
{vm_xml}
\t\t\t</VMs>
\t\t</host></hosts>
\t</datacenter>""")
    return '<?xml version="1.0"?>\n<edge_devices>\n' + "\n".join(dcs) + "\n</edge_devices>\n"


def main() -> None:
    (CONFIG / "default_config.properties").write_text(properties(), encoding="utf-8")
    (CONFIG / "applications.xml").write_text(applications(), encoding="utf-8")
    (CONFIG / "edge_devices.xml").write_text(edge_devices(), encoding="utf-8")
    print(f"wrote {len(list(CONFIG.iterdir()))} config files to {CONFIG}")


if __name__ == "__main__":
    main()
